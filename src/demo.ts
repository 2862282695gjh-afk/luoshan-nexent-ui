export function demoAnswer(query: string) {
  if (/入驻|流程/.test(query)) return welcomeAnswer
  if (/补贴|政策/.test(query))
    return `### 园区补贴政策咨询\n\n可重点了解以下政策方向：\n\n- **企业发展：** 科技型企业培育、研发投入与创新项目支持。\n- **人才服务：** 人才引进、住房及就业服务。\n- **办公空间：** 符合条件企业的租金或孵化服务支持。\n\n> 这是演示内容，不代表罗山科技园现行政策。连接园区智能体后，可根据园区知识库查询具体条件、申报期限和材料。`
  if (/会议室/.test(query))
    return `### 会议室预约\n\n1. 准备会议日期、起止时间和预计人数。\n2. 说明投影、视频会议等设备需求。\n3. 在园区预约系统中查看空闲时段并提交申请。\n4. 收到确认后，按时使用并办理离场。\n\n> 演示模式无法查询实时空闲情况或代为预约，请连接园区智能体后咨询。`
  if (/报修|电话/.test(query))
    return `### 物业报修咨询\n\n报修时，建议提供 **楼栋与房间号、故障描述、现场照片和联系人**，以便物业快速定位问题。\n\n当前为演示模式，没有园区已核实的联系电话。请通过园区物业服务台或园区公示的联系方式报修。`
  return `您提出了「${query.replace(/[<>]/g, '')}」。\n\n当前处于 **演示模式**，可以体验多轮对话、历史记录、搜索、重命名与停止生成。\n\n点击右上角的「连接设置」，按说明配置 Nexent 北向服务后，这里的回答将由您选择的已发布智能体实时生成。`
}
export function seedConversations(): Conversation[] {
  const now = Date.now()
  const titles = [
    '入驻流程问答',
    '合同模板对比',
    '物业报修流程咨询',
    '数据问数：上月入驻',
    '200页产业政策白皮书',
    '物业报修流程咨询',
  ]
  return titles.map((title, i) => ({
    id: -i - 1,
    title,
    time: now - (i < 2 ? 0 : i < 5 ? 86400000 : 4 * 86400000),
    messages: [
      { id: `u-${i}`, role: 'user', content: i === 0 ? '入驻流程问答' : title },
      { id: `a-${i}`, role: 'assistant', content: i === 0 ? welcomeAnswer : demoAnswer(title) },
    ],
  }))
}
